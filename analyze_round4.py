import json
import os
import re
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from analyze import COLORS, GRID, INK, INK2, KIND  # noqa: E402
from round3_lib import spearman  # noqa: E402

VARS = ["raw", "center", "zscore", "abtt1", "abtt3", "abtt10"]
POOLS = {"mean": "mean pooling", "eol": "PromptEOL"}
DSETS = {"stsb": "STS-B", "sickr": "SICK-R"}


def slugs():
    return [os.path.basename(l.strip()) for l in open("models.txt") if l.strip()]


# ---------------------------------------------------------------- A: STS

def part_a():
    S = slugs()
    R = {s: json.load(open(f"results/round4/sts/{s}.json")) for s in S if os.path.exists(f"results/round4/sts/{s}.json")}
    S = [s for s in S if s in R]
    r3 = {s: json.load(open(f"results/round3/{s}.json"))["step1"] for s in S}
    dA = {s: r3[s]["V1"]["all"]["isotropy_full"] - r3[s]["V3"]["all"]["isotropy_full"] for s in S}
    out = {"models": S, "check": {}, "A2": {}, "A3": {}, "A4": {}, "layers": {}}
    L = ["# Round 4 A: STS with V1 vs V3 (generated by analyze_round4.py)\n",
         "Spearman(cos, gold) × 100. Statistics for center / zscore / abtt-k are fitted on 2000 WikiText sentences "
         "(data/fit_sentences.jsonl), never on STS data.\n", "## Checks\n",
         "| model | 0a max rel err (V3 vs hidden_states[-1]) | A1 max \\|V1 − V3\\| under zscore | "
         "STS-B raw: V3 (fp64 recon) vs hidden_states[-1], mean / eol |", "|---|---|---|---|"]
    for s in S:
        r = R[s]
        out["check"][s] = {"0a": r["check0a_max_rel_err"], "A1": r["checkA1_zscore_max_abs_delta"]}
        L.append(f"| {s} | {r['check0a_max_rel_err']:.1e} | {r['checkA1_zscore_max_abs_delta']:.1e} | "
                 + " / ".join(f"{r['scores'][f'stsb/{p}/V3/raw']:.2f} vs {r['scores'][f'stsb/{p}/V3hs/raw']:.2f}"
                              for p in POOLS) + " |")
    for ds in DSETS:
        for p in POOLS:
            L += [f"\n## Table A: {DSETS[ds]}, {POOLS[p]} (V1 / V3)\n",
                  "| model | " + " | ".join(VARS) + " |", "|---" * (1 + len(VARS)) + "|"]
            for s in S:
                sc = R[s]["scores"]
                L.append(f"| {s} | " + " | ".join(f"{sc[f'{ds}/{p}/V1/{v}']:.1f} / {sc[f'{ds}/{p}/V3/{v}']:.1f}"
                                                  for v in VARS) + " |")
    L += ["\n## V1 − V3 with paired-bootstrap 95% CI (1000 resamples of pairs)\n",
          "| model | A_V1 − A_V3 | " + " | ".join(f"{DSETS[ds]} {p} raw" for ds in DSETS for p in POOLS) + " | "
          + " | ".join(f"{DSETS[ds]} {p} center" for ds in DSETS for p in POOLS) + " |", "|---" * 10 + "|"]
    for s in S:
        dl = R[s]["delta"]
        cell = lambda k: f"{dl[k]['delta']:+.1f} [{dl[k]['ci_lo']:+.1f}, {dl[k]['ci_hi']:+.1f}]"  # noqa: E731
        L.append(f"| {s} | {dA[s]:+.3f} | " + " | ".join(cell(f"{ds}/{p}/raw") for ds in DSETS for p in POOLS) + " | "
                 + " | ".join(cell(f"{ds}/{p}/center") for ds in DSETS for p in POOLS) + " |")
    # A2
    L.append("\n## A2: Spearman across models of ΔSTS(V1 − V3) vs (A_V1 − A_V3)\n")
    L += ["| setting | raw ρ (p) | center ρ (p) | models with CI excluding 0 (raw): V1 better / V3 better |", "|---|---|---|---|"]
    for ds in DSETS:
        for p in POOLS:
            row = {}
            for v in ("raw", "center"):
                row[v] = spearman([R[s]["delta"][f"{ds}/{p}/{v}"]["delta"] for s in S], [dA[s] for s in S])[:2]
            better = sum(R[s]["delta"][f"{ds}/{p}/raw"]["ci_lo"] > 0 for s in S)
            worse = sum(R[s]["delta"][f"{ds}/{p}/raw"]["ci_hi"] < 0 for s in S)
            out["A2"][f"{ds}/{p}"] = {"raw": row["raw"], "center": row["center"], "V1_better": better, "V3_better": worse}
            L.append(f"| {DSETS[ds]} {POOLS[p]} | {row['raw'][0]:+.3f} ({row['raw'][1]:.2g}) | "
                     f"{row['center'][0]:+.3f} ({row['center'][1]:.2g}) | {better} / {worse} |")
    # exploratory (added after seeing A2): gamma's effect on variance concentration instead of on the mean
    dT = {s: r3[s]["V3"]["all"]["top1_var"] - r3[s]["V1"]["all"]["top1_var"] for s in S}
    dRk = {s: r3[s]["V1"]["all"]["rankme_over_d_norm"] - r3[s]["V3"]["all"]["rankme_over_d_norm"] for s in S}
    L += ["\n### Exploratory (not a preset hypothesis): ΔSTS(V1 − V3, raw) vs γ's effect on variance concentration\n",
          "top1 = top-1 variance share of the centered bank (round 3); R = Gaussian-normalized RankMe/d.\n",
          "| setting | ρ vs top1(V3) − top1(V1) (p) | ρ vs R(V1) − R(V3) (p) |", "|---|---|---|"]
    out["A2_exploratory"] = {}
    for ds in DSETS:
        for p in POOLS:
            y = [R[s]["delta"][f"{ds}/{p}/raw"]["delta"] for s in S]
            a, b = spearman(y, [dT[s] for s in S])[:2], spearman(y, [dRk[s] for s in S])[:2]
            out["A2_exploratory"][f"{ds}/{p}"] = {"top1": a, "rankme": b}
            L.append(f"| {DSETS[ds]} {POOLS[p]} | {a[0]:+.3f} ({a[1]:.2g}) | {b[0]:+.3f} ({b[1]:.2g}) |")
    # A3: how much of the gain does centering give, and does it close the V1/V3 gap
    L += ["\n## A3: centering\n",
          "gain = center − raw; share = (center − raw) / (best of the 6 variants − raw), when best > raw; "
          "gap = \\|V1 − V3\\|.\n",
          "| model | " + " | ".join(f"{DSETS[ds]} {p}: gain V1 / V3; gap raw → center" for ds in DSETS for p in POOLS) + " |",
          "|---" * 5 + "|"]
    shares, closes = [], []
    for s in S:
        sc = R[s]["scores"]
        cells = []
        for ds in DSETS:
            for p in POOLS:
                g = {V: sc[f"{ds}/{p}/{V}/center"] - sc[f"{ds}/{p}/{V}/raw"] for V in ("V1", "V3")}
                for V in ("V1", "V3"):
                    best = max(sc[f"{ds}/{p}/{V}/{v}"] for v in VARS)
                    if best - sc[f"{ds}/{p}/{V}/raw"] > 0.5:
                        shares.append(g[V] / (best - sc[f"{ds}/{p}/{V}/raw"]))
                gr = abs(sc[f"{ds}/{p}/V1/raw"] - sc[f"{ds}/{p}/V3/raw"])
                gc = abs(sc[f"{ds}/{p}/V1/center"] - sc[f"{ds}/{p}/V3/center"])
                closes.append(gc < gr)
                cells.append(f"{g['V1']:+.1f} / {g['V3']:+.1f}; {gr:.1f} → {gc:.1f}")
        L.append(f"| {s} | " + " | ".join(cells) + " |")
    out["A3"] = {"median_share_of_best_gain": float(np.median(shares)) if shares else None, "n_share": len(shares),
                 "frac_gap_reduced": float(np.mean(closes)), "n_gap": len(closes)}
    L.append(f"\nMedian share of the best variant's gain obtained by centering: {out['A3']['median_share_of_best_gain']:.2f} "
             f"(n = {len(shares)} model × V × setting cells with best − raw > 0.5); centering reduced the V1/V3 gap in "
             f"{sum(closes)}/{len(closes)} model × setting cells.\n")
    # A4: abtt-k relative to center
    L += ["## A4: abtt-k − center (V3; V1 in parentheses)\n",
          "| model | A_V3 | " + " | ".join(f"{DSETS[ds]} {p}: k=1 / 3 / 10" for ds in DSETS for p in POOLS) + " |",
          "|---" * 6 + "|"]
    for s in S:
        sc = R[s]["scores"]
        cells = []
        for ds in DSETS:
            for p in POOLS:
                cells.append(" / ".join(
                    f"{sc[f'{ds}/{p}/V3/abtt{k}'] - sc[f'{ds}/{p}/V3/center']:+.1f} "
                    f"({sc[f'{ds}/{p}/V1/abtt{k}'] - sc[f'{ds}/{p}/V1/center']:+.1f})" for k in (1, 3, 10)))
        out["A4"][s] = {f"{ds}/{p}/{V}/abtt{k}": sc[f"{ds}/{p}/{V}/abtt{k}"] - sc[f"{ds}/{p}/{V}/center"]
                        for ds in DSETS for p in POOLS for V in ("V1", "V3") for k in (1, 3, 10)}
        L.append(f"| {s} | {r3[s]['V3']['all']['isotropy_full']:.3f} | " + " | ".join(cells) + " |")
    # layer sweep
    L += ["\n## Layer sweep (raw hidden_states[l]; raw / center)\n",
          "best = the block with the highest centered score (layer index / L, blocks 1..L); last = hidden_states[-1] (= V3, bf16); "
          "emb = hidden_states[0] (token embeddings; mean pooling only, PromptEOL ends on the same token for every sentence).\n",
          "| model | " + " | ".join(f"{DSETS[ds]} {p} center: best (layer) / last / V1 last" for ds in DSETS for p in POOLS) + " |",
          "|---" * 5 + "|"]
    for s in S:
        lay = R[s]["layers"]
        nL = max(int(k.split("/")[2]) for k in lay)
        cells = []
        for ds in DSETS:
            for p in POOLS:
                vals = [lay[f"{ds}/{p}/{l}/center"] for l in range(nL + 1)]
                # layer 0 is the token embedding: for PromptEOL every sentence ends on the same token (NaN), so the
                # best layer is searched over blocks 1..L; the embedding-layer score is reported separately
                b = 1 + int(np.nanargmax(vals[1:]))
                out["layers"][f"{s}/{ds}/{p}"] = {"best_layer": b, "n_layers": nL, "best": vals[b], "last": vals[-1],
                                                  "V1_last": R[s]["scores"][f"{ds}/{p}/V1/center"],
                                                  "curve": vals, "curve_raw": [lay[f"{ds}/{p}/{l}/raw"] for l in range(nL + 1)]}
                cells.append(f"{vals[b]:.1f} ({b}/{nL}) / {vals[-1]:.1f} / {R[s]['scores'][f'{ds}/{p}/V1/center']:.1f}"
                             + (f" / emb {vals[0]:.1f}" if p == "mean" else ""))
        L.append(f"| {s} | " + " | ".join(cells) + " |")
    open("results/round4/sts_summary.md", "w").write("\n".join(L) + "\n")
    json.dump(out, open("results/round4/sts_analysis.json", "w"), indent=1)
    fig_a1(S, R, dA, "figs/r4_figA1_dsts_vs_dA.png")
    print("wrote results/round4/sts_summary.md, sts_analysis.json, figs/r4_figA1_dsts_vs_dA.png")


def fig_a1(S, R, dA, path):
    fig, axes = plt.subplots(2, 2, figsize=(11, 8.4), sharex=True)
    for i, ds in enumerate(DSETS):
        for j, p in enumerate(POOLS):
            ax = axes[i][j]
            x = np.array([dA[s] for s in S])
            d = [R[s]["delta"][f"{ds}/{p}/raw"] for s in S]
            y = np.array([e["delta"] for e in d])
            yerr = np.array([[e["delta"] - e["ci_lo"] for e in d], [e["ci_hi"] - e["delta"] for e in d]])
            base = np.array([KIND.get(s, "") == "base" for s in S])
            for mask, col, lab in ((base, COLORS[0], "base"), (~base, COLORS[1], "post-trained")):
                ax.errorbar(x[mask], y[mask], yerr=yerr[:, mask], fmt="o", ms=6, color=col, ecolor=col,
                            elinewidth=1.2, capsize=2, label=lab)
            for s, xx, yy in zip(S, x, y):
                ax.annotate(s.replace("-Instruct", "-I").replace("-2501", "").replace("Mistral-Small-", "Mistral-"),
                            (xx, yy), xytext=(4, 3), textcoords="offset points", fontsize=7, color=INK2)
            ax.axhline(0, color=GRID, lw=1)
            ax.axvline(0, color=GRID, lw=1)
            rho, pv, _ = spearman(y, x)
            ax.set_title(f"{DSETS[ds]}, {POOLS[p]} — Spearman ρ = {rho:+.2f} (p = {pv:.2g})", fontsize=9.5,
                         loc="left", color=INK)
            if i == 1:
                ax.set_xlabel("A(V1) − A(V3)  (round-3 isotropy, last layer)")
            if j == 0:
                ax.set_ylabel("ΔSTS = V1 − V3, raw cosine (×100)")
    axes[0][0].legend(fontsize=8.5, loc="upper left")
    fig.suptitle("Does using V1 instead of V3 help where γ shrank isotropy? (95% paired-bootstrap CIs)",
                 x=0.01, ha="left", color=INK)
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)


# ---------------------------------------------------------------- B: training dynamics

DYN_MODELS = ["pythia-70m", "pythia-160m", "pythia-410m", "pythia-1.4b", "OLMo-2-0425-1B"]
PYTHIA_TOK_PER_STEP = 1024 * 2048  # Pythia: batch 1024 sequences x 2048 tokens


def ckpt_order():
    rows = [l.rstrip("\n").split("\t") for l in open("configs/round4_ckpts.tsv") if l.strip()]
    out = {}
    for repo, rev in rows:
        out.setdefault(repo.split("/")[1], []).append(rev)
    return out


def tokens_b(model, rev):
    """Training tokens seen, in billions (OLMo-2 main = end of stage 1 + the 50B-token stage-2 mix)."""
    if model.startswith("pythia"):
        return int(rev[4:]) * PYTHIA_TOK_PER_STEP / 1e9
    if rev == "main":
        return 4001 + 51
    return float(re.search(r"tokens(\d+)B", rev).group(1))


def step_of(model, rev):
    if model.startswith("pythia"):
        return int(rev[4:])
    return None if rev == "main" else int(re.search(r"step(\d+)", rev).group(1))


def load_dyn():
    D = {}
    for m, revs in ckpt_order().items():
        for rev in revs:
            fn = f"results/round4/dyn/{m}/{rev}.json"
            if os.path.exists(fn):
                D.setdefault(m, []).append(json.load(open(fn)))
    return D


def row_stats(r, prev=None):
    s1, gb, dc, fn = r["step1"], r["gamma_beta"], r["decomp"], r["function"]
    mid = [x for x in r["massive"] if 0 < x["layer"] < r["n_layers"]]
    top = max(mid, key=lambda x: x["outlier_ratio"])
    sets = fn["sets"]
    canc = [(k, sets[f"top{k}"]["corr_S_R"], sets[f"top{k}"]["dloss"]) for k in (1, 2, 4, 8, 16, 32)]
    return {
        "A_V1": s1["V1"]["all"]["isotropy_full"], "A_V3": s1["V3"]["all"]["isotropy_full"],
        "ub_V1": dc["ubar_sq_V1"], "ub_V3": dc["ubar_sq_V3"],
        "Brc_V3": s1["V3"]["all"]["cross_cos_robust_centered"],
        "R_V1": s1["V1"]["all"]["rankme_over_d_norm"], "R_V3": s1["V3"]["all"]["rankme_over_d_norm"],
        "g_maxmed": gb["gamma_max_over_median"], "g_norm": gb["gamma_norm"], "b_norm": gb["beta_norm"],
        "b_over_g": gb["beta_over_gamma"],
        "cum10_V3": dc["cum_V3"]["10"], "cum10_V1": dc["cum_V1"]["10"],
        "v1pct_med": float(np.median(dc["v1_share_pct_of_V3_top10"])),
        "gpct_med": float(np.median(dc["gamma_pct_of_V3_top10"])),
        "overlap_prev": len(set(dc["top10_V3"]) & set(prev["decomp"]["top10_V3"])) if prev else None,
        "loss": fn["loss_base"], "dl_all": sets["all"]["dloss"], "dl_top1": sets["top1"]["dloss"],
        "dl_top8": sets["top8"]["dloss"], "dl_top32": sets["top32"]["dloss"],
        "add10": float(sum(x["additive_share"] for x in fn["per_dim_top10"])),
        "min_corr": min(c for _, c, _ in canc),
        "cancel_k": [k for k, c, dl in canc if c < 0 and dl > sets["all"]["dloss"]],
        "bark": [x["dim"] for x in fn["per_dim_top10"]
                 if x["contrib_V3"] >= 0.3 and abs(x["additive_share"]) < 0.05
                 and x["offset_sd"] < 0.05 * max(x["offset_absmean"], 1e-12)],
        "top1_dim": fn["per_dim_top10"][0]["dim"], "top1_contrib": fn["per_dim_top10"][0]["contrib_V3"],
        "top1_add": fn["per_dim_top10"][0]["additive_share"],
        "top1_sd_over_mean": fn["per_dim_top10"][0]["offset_sd"] / max(fn["per_dim_top10"][0]["offset_absmean"], 1e-12),
        "mass_ratio": top["outlier_ratio"], "mass_layer": top["layer"],
        "mass_gpct": float(np.median(top["top5_gamma_pct"])), "mass_dims": top["top5_dims"],
        "pos0_max": max(x["pos0_ratio_median"] for x in r["massive"] if x["layer"] < r["n_layers"]),
        "checks": (r["check0a"]["max_rel_err"], r["fold"]["max_rel_err"], r["fold"]["argmax_agree"]),
    }


def xpos(model, rev):
    """x position on a log token axis; step 0 is drawn one decade left of the first positive checkpoint."""
    t = tokens_b(model, rev)
    return t if t > 0 else (2e-4 if model.startswith("pythia") else 0.2)


def part_b():
    D = load_dyn()
    T = {m: [] for m in D}
    for m, rs in D.items():
        prev = None
        for r in rs:
            T[m].append({"rev": r["revision"], "step": step_of(m, r["revision"]), "tokens_B": tokens_b(m, r["revision"]),
                         **row_stats(r, prev)})
            prev = r
    json.dump({"rows": T, "arch": {m: {k: D[m][-1][k] for k in ("norm_module", "norm_type", "has_beta", "tied",
                                                                 "head_is_input_embedding", "head_bias", "n_layers",
                                                                 "d", "vocab_head", "vocab_tok", "bos_token_id",
                                                                 "first_token_is_bos_frac")} for m in D}},
              open("results/round4/dyn_analysis.json", "w"), indent=1)
    L = ["# Round 4 B: training dynamics (generated by analyze_round4.py)\n",
         "A = isotropy (full sequences); ub = ‖ū‖² (bank); R = RankMe/d ÷ Gaussian; γ max/med = max/median \\|γ\\|; "
         "cum10 = top-10 share of ‖ū‖² (V3); v1pct / γpct = median over V3 top-10 dims of their V1 mean-share / \\|γ\\| "
         "percentile; ov = top-10 overlap with the previous checkpoint; add10 = additive share of the top-10 offsets; "
         "minc = min_k corr(δ_S, δ_R); mass = max over middle layers of max/median mean\\|h\\| (layer) and the median "
         "\\|γ\\| percentile of that layer's top-5 dims; pos0 = max over layers (excluding the last) of median "
         "‖h₀‖ / median ‖h_t‖.\n", "## Checks\n", "| model | checkpoints | max 0a | max fold rel err | min argmax agree |",
         "|---|---|---|---|---|"]
    for m, rows in T.items():
        c = np.array([r["checks"] for r in rows])
        L.append(f"| {m} | {len(rows)} | {c[:, 0].max():.1e} | {c[:, 1].max():.1e} | {c[:, 2].min():.5f} |")
    for m, rows in T.items():
        L += [f"\n## {m}\n",
              "| rev | tokens (B) | A V1 / V3 | ub V1 / V3 | R V1 / V3 | γ max/med | ‖β‖/‖γ‖ | cum10 | v1pct / γpct | ov | "
              "loss | Δall / top1 / top8 / top32 | add10 | minc | top-1 dim (share, add, sd/\\|mean\\|) | mass (layer) / γpct | pos0 |",
              "|---" * 17 + "|"]
        for r in rows:
            bo = "–" if r["b_over_g"] is None else f"{r['b_over_g']:.3f}"
            L.append(f"| {r['rev']} | {r['tokens_B']:.3g} | {r['A_V1']:.3f} / {r['A_V3']:.3f} | {r['ub_V1']:.3f} / {r['ub_V3']:.3f} | "
                     f"{r['R_V1']:.2f} / {r['R_V3']:.2f} | {r['g_maxmed']:.1f} | {bo} | {r['cum10_V3']:.2f} | "
                     f"{r['v1pct_med']:.2f} / {r['gpct_med']:.2f} | {'' if r['overlap_prev'] is None else r['overlap_prev']} | "
                     f"{r['loss']:.3f} | {r['dl_all']:+.3f} / {r['dl_top1']:+.3f} / {r['dl_top8']:+.3f} / {r['dl_top32']:+.3f} | "
                     f"{r['add10']:+.2f} | {r['min_corr']:+.2f} | {r['top1_dim']} ({r['top1_contrib']:.2f}, "
                     f"{r['top1_add']:+.3f}, {r['top1_sd_over_mean']:.3f}) | {r['mass_ratio']:.0f} ({r['mass_layer']}) / "
                     f"{r['mass_gpct']:.2f} | {r['pos0_max']:.1f} |")
    open("results/round4/dyn_summary.md", "w").write("\n".join(L) + "\n")
    figs_b(T)
    print("wrote results/round4/dyn_summary.md, dyn_analysis.json, figs/r4_figB*.png")


