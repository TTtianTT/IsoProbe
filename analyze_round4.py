def figs_b(T):
    ms = [m for m in DYN_MODELS if m in T]
    # B1: isotropy V1 / V3, gamma peakiness, beta/gamma (shared log-token x axis; one measure per row, no dual axes)
    fig, axes = plt.subplots(3, len(ms), figsize=(3.1 * len(ms), 7.6), sharex="col", squeeze=False)
    for j, m in enumerate(ms):
        rows = T[m]
        x = [xpos(m, r["rev"]) for r in rows]
        a = axes[0][j]
